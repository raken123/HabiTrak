// Flatten an ES-module app into one classic script.
//
// A WebView loading from file:///android_asset/ has an opaque origin, and
// Chromium refuses module scripts there. Rather than ship a web server inside
// the app to give the page a real origin, the module graph is resolved here and
// emitted as a single classic script.
//
// Each module keeps its own scope in an IIFE and publishes its exports into a
// registry, so nothing collides — two modules in this graph both define
// `clamp`, and a naive concatenation would break on that alone.
//
//   node scripts/bundle-assets.mjs <entry.js> <out.js>

import fs from 'node:fs';
import path from 'node:path';

const IMPORT_RE = /^[ \t]*import\s+(?:\{([^}]*)\}|\*\s+as\s+([\w$]+))\s+from\s*['"]([^'"]+)['"];?[ \t]*$/gm;
const BARE_RE = /^[ \t]*import\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const EXPORT_DECL_RE = /^([ \t]*)export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gm;
const EXPORT_LIST_RE = /^[ \t]*export\s*\{([^}]*)\};?[ \t]*$/gm;

const [entryArg, outArg] = process.argv.slice(2);
if (!entryArg || !outArg) throw new Error('usage: bundle-assets.mjs <entry.js> <out.js>');

const entry = path.resolve(entryArg);
const base = path.dirname(entry);
const id = (file) => path.relative(base, file).replace(/\\/g, '/');

function wrap(file) {
  let src = fs.readFileSync(file, 'utf8');
  const deps = [];
  const exported = new Set();

  src = src.replace(BARE_RE, (_, spec) => {
    const dep = path.resolve(path.dirname(file), spec);
    deps.push(dep);
    return `__M[${JSON.stringify(id(dep))}];`;
  });

  src = src.replace(IMPORT_RE, (_, named, namespace, spec) => {
    const dep = path.resolve(path.dirname(file), spec);
    if (!fs.existsSync(dep)) throw new Error(`${id(file)} imports ${spec}, which does not exist`);
    deps.push(dep);
    const from = `__M[${JSON.stringify(id(dep))}]`;
    if (namespace) return `var ${namespace} = ${from};`;
    const bindings = named.split(',').map((part) => {
      const [name, alias] = part.trim().split(/\s+as\s+/).map((s) => s.trim());
      return alias ? `${name}: ${alias}` : name;
    }).filter(Boolean).join(', ');
    return `var { ${bindings} } = ${from};`;
  });

  for (const m of src.matchAll(/^[ \t]*export\s+(?:async\s+)?(?:function|class|const|let|var)\s+([\w$]+)/gm)) {
    exported.add(m[1]);
  }
  src = src.replace(EXPORT_DECL_RE, '$1');

  src = src.replace(EXPORT_LIST_RE, (_, list) => {
    for (const part of list.split(',')) {
      const [name, alias] = part.trim().split(/\s+as\s+/).map((s) => s.trim());
      if (name) exported.add(alias || name);
    }
    return '';
  });

  const leftover = /^\s*export\s.*$/m.exec(src);
  if (leftover) throw new Error(`${id(file)}: unsupported export form — ${leftover[0].trim()}`);

  const returns = [...exported].map((n) => `${n}: ${n}`).join(', ');
  return {
    deps: [...new Set(deps)],
    body: `__M[${JSON.stringify(id(file))}] = (function () {\n${src}\nreturn { ${returns} };\n})();`,
  };
}

const seen = new Set();
const chunks = [];
(function emit(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const { deps, body } = wrap(file);
  for (const dep of deps) emit(dep);
  chunks.push(body);
})(entry);

const out = `// Generated by scripts/bundle-assets.mjs — do not edit.
// ${seen.size} modules, flattened for a context that cannot load ES modules.
(function () {
"use strict";
var __M = Object.create(null);
${chunks.join('\n')}
})();
`;

fs.mkdirSync(path.dirname(path.resolve(outArg)), { recursive: true });
fs.writeFileSync(outArg, out);
console.log(`bundled ${seen.size} modules -> ${outArg} (${(out.length / 1024).toFixed(0)} KB)`);
